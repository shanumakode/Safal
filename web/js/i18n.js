export function t(key, vars, lang = state.lang) {
  let str = STR[lang]?.[key] ?? STR.en[key] ?? key;
  if (vars) str = str.replace(/\{(\w+)\}/g, (m, k) => (vars[k] ?? m));
  return str;
}

// Pick a *_en / *_hi field from a data object; fall back to English.
export function pick(obj, base, lang = state.lang) {
  if (!obj) return null;
  return obj[`${base}_${lang}`] ?? obj[`${base}_en`] ?? obj[base] ?? null;
}

export function pickList(obj, base, lang = state.lang) {
  const v = pick(obj, base, lang);
  return Array.isArray(v) ? v : [];
}

export function siteName(g, lang = state.lang) {
  return (lang === 'hi' && g.site_hi) || g.site;
}

export function formatDate(iso, lang = state.lang) {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return String(iso ?? '');
  return d.toLocaleString(lang === 'hi' ? 'hi-IN' : 'en-IN', { day: 'numeric', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit' });
}
